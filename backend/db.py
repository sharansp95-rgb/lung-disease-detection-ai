"""
Persistence: three tables (users, tokens, scans). SQLite (one file, app.db)
by default; Postgres via psycopg 3 when DATABASE_URL is set (hosted deploys,
whose disk isn't persistent). Uses plain DB-API calls rather than an ORM --
schema is small and stable enough not to need one, and it keeps the
dependency list short.

Callers write SQLite-style SQL ("?" placeholders, INSERT ... RETURNING id)
and read rows by column name; get_db() hides the differences:
  - Postgres connections translate "?" to "%s" and return dict rows.
  - The schema swaps AUTOINCREMENT / datetime('now') / REAL for their
    Postgres equivalents. created_at stays TEXT in the same
    'YYYY-MM-DD HH:MM:SS' (UTC) format on both, so ordering and API output
    are identical. Booleans stay INTEGER 0/1 on both.

Connections are opened per-call (no pooling) -- fine at our request volume.
"""

import sqlite3
from contextlib import contextmanager

from config import DATABASE_URL, DB_PATH

USE_POSTGRES = bool(DATABASE_URL)

_SCHEMA_TEMPLATE = """
CREATE TABLE IF NOT EXISTS users (
    id {id_column},
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    email_verified INTEGER NOT NULL DEFAULT 0,
    google_id TEXT UNIQUE,
    display_name TEXT,
    created_at TEXT NOT NULL DEFAULT {now}
);

CREATE TABLE IF NOT EXISTS tokens (
    id {id_column},
    user_id INTEGER NOT NULL REFERENCES users(id),
    token TEXT UNIQUE NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('verify', 'reset')),
    expires_at TEXT NOT NULL,
    used INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT {now}
);

CREATE TABLE IF NOT EXISTS scans (
    id {id_column},
    user_id INTEGER NOT NULL REFERENCES users(id),
    modality TEXT NOT NULL,
    predicted_class TEXT NOT NULL,
    confidence {float_type} NOT NULL,
    class_probabilities TEXT NOT NULL,
    heatmap_png_base64 TEXT NOT NULL,
    report TEXT,
    report_source TEXT,
    created_at TEXT NOT NULL DEFAULT {now}
);
"""

SQLITE_SCHEMA = _SCHEMA_TEMPLATE.format(
    id_column="INTEGER PRIMARY KEY AUTOINCREMENT",
    now="(datetime('now'))",
    float_type="REAL",
)

POSTGRES_SCHEMA = _SCHEMA_TEMPLATE.format(
    id_column="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    now="(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))",
    float_type="DOUBLE PRECISION",
)


class _PostgresConnection:
    """Just enough of sqlite3.Connection's interface for this app."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        # None of this app's queries contain a literal "?" or "%".
        return self._conn.execute(sql.replace("?", "%s"), params)


@contextmanager
def get_db():
    if USE_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row

        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        try:
            yield _PostgresConnection(conn)
            conn.commit()
        finally:
            conn.close()
        return

    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def init_db():
    with get_db() as conn:
        if USE_POSTGRES:
            for statement in POSTGRES_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
        else:
            conn.executescript(SQLITE_SCHEMA)
